; ROM $0A53 (IP $0653, раз за кадр) — KERNEL_SPRITE_CLEAR (вход NATIVE, страница HOST2_PAGE: в резиденте и
; нативной странице места нет): свободные записи памяти спрайтов с [2EFC] до #3C0 — слова +4 и +6 = 0 (шаг 8). На
; выходе BX — первое значение ≥ #3C0 (или [2EFC], если уже ≥), AX = 0, DS прежний; флаги после RET не живут.
; VDAC2+ (2026-09-25, скорость): при [2EFC], кратном 8, — развёрнутая цепочка LD (nn),HL с записи [2EFC] / 8: 32 такта
; на запись вместо ≈70 у цикла. Обнулять надо весь хвост, как ROM: $1CA6 кладёт части многоклеточной записи выше
; указателя (ловушка записи эталона, 25.09), и граница «прошлой очистки» на боссе этапа 4 разошлась с эталоном.
KERNEL_SPRITE_CLEAR:
                ld hl,(V_DS)
                ld de,#4000
                or a
                sbc hl,de
                jr z,.clear0
                ld a,$$K_00A53
                ld hl,K_00A53
                jp FARJP
.clear0:        ld hl,0
                ld (V_AX),hl                    ; AX = 0
                ld a,#30
                ld (W2_PAGE),a
                ld a,V30_PAGE_BASE+#30
                ld bc,PORT_PAGE2
                out (c),a
                ld de,(#4000+#2EFC)             ; BX = [2EFC]
                ld hl,#3C0-1
                or a
                sbc hl,de                       ; HL = #3BF − BX; CF — BX ≥ #3C0: записей нет
                jr c,.done
                ld a,e
                and 7
                jr nz,.loop                     ; BX не кратен 8 — циклом, как прежде
                ld hl,#3C0
                ld (V_BX),hl                    ; BX после цикла ROM: #3C0
                ld h,d
                ld l,e
                srl h
                rr l
                srl h
                rr l                            ; BX / 4
                ld b,h
                ld c,l
                add hl,hl
                add hl,bc                       ; BX·3/4 = (BX / 8)·6 — шесть байт команд на запись
                ld bc,SC_CHAIN
                add hl,bc
                push hl                         ; вход цепочки — RET ниже
                ld hl,0
                ret
.loop:          ld a,l
                srl h
                rra
                srl h
                rra
                srl h
                rra                             ; A = (#3BF − BX) >> 3 (≤ #77)
                inc a
                ld b,a                          ; B — записей: ⌈(#3C0 − BX) / 8⌉
                ld hl,#8004
                add hl,de                       ; HL → [bx+4] в окне W2
                ld de,5
                xor a
.clear:         ld (hl),a
                inc hl
                ld (hl),a
                inc hl
                ld (hl),a
                inc hl
                ld (hl),a                       ; [bx+4] = [bx+6] = 0
                add hl,de                       ; следующая запись
                djnz .clear
                ld de,-#8004
                add hl,de
                ex de,hl                        ; DE = BX после цикла (первое значение ≥ #3C0)
.done:          ld (V_BX),de
                pop de                          ; RET V30
                jp DISPATCH
